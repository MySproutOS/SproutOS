/*
 * CommonJS on purpose.
 *
 * kysely-codegen loads this through cosmiconfig's *synchronous* explorer. Given a
 * `.ts` config, cosmiconfig reaches for the TypeScript compiler API and calls
 * `typescript.findConfigFile`, which TypeScript 7 removed — the same TS 6/7 split
 * that forced `tools/openapi` into its own workspace. A `.cjs` config is loaded by
 * plain `require`, so no compiler is involved and the repo can stay on TypeScript 7.
 *
 * `.mjs` would not work either: the sync explorer cannot `await import()`.
 *
 * Default configuration: https://github.com/RobinBlomberg/kysely-codegen/releases/tag/0.18.0
 */
const { TypeScriptSerializer, transform } = require("kysely-codegen")

class Serializer extends TypeScriptSerializer {
  constructor(options = {}) {
    super(options)
    // https://github.com/RobinBlomberg/kysely-codegen/issues/229#issuecomment-2762149908
    this.serializeFile = this.serializeFile.bind(this)
  }

  serializeFile(metadata, dialect, options) {
    let data = ""

    if (!this.skipAutogeneratedFileComment) {
      data += "/**\n"
      data += " * This file was generated by kysely-codegen.\n"
      data += " * Please do not edit it manually.\n"
      data += " */\n\n"
    }

    data += this.serializeStatements(
      transform({
        camelCase: options?.camelCase,
        defaultSchemas: options?.defaultSchemas,
        dialect,
        metadata,
        overrides: options?.overrides,
        runtimeEnums: this.runtimeEnums,
      }),
    )

    return data
  }
}

module.exports = {
  envFile: `${__dirname}/../../../.env`,
  logLevel: "warn",
  outFile: `${__dirname}/../src/types.ts`,
  url: "env(DATABASE_URL)",
  camelCase: true,
  serializer: new Serializer({
    runtimeEnums: true,
    singularize: false,
    skipAutogeneratedFileComment: false,
    typeOnlyImports: true,
  }),
}
